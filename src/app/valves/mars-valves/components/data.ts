export function getPortTypes(s: MarsSeriesDTO): string[] {
  const p = s.portType.toLowerCase()
  const out: string[] = []
  if (p.includes('full')) out.push('Full Port')
  if (p.includes('reduced')) out.push('Reduced Port')
  return out
}

export function getEndConnections(s: MarsSeriesDTO): string[] {
  const e = s.ends.toLowerCase()
  const out: string[] = []
  if (e.includes('npt') || e.includes('bsp') || e.includes('threaded')) out.push('Threaded')
  if (e.includes('flange')) out.push('Flanged')
  if (e.includes('butt weld') || e.includes('socket weld') || e.includes('orbital')) out.push('Welded')
  if (e.includes('wafer')) out.push('Wafer')
  if (e.includes('tri-clamp') || e.includes('tube')) out.push('Sanitary (Tri-Clamp / Tube)')
  return out
}

export function getOptionTags(s: MarsSeriesDTO): string[] {
  const out: string[] = []
  if (s.options.some(o => o.toLowerCase().includes('v-port'))) out.push('V-Port Flow Control')
  if (s.options.some(o => o.toLowerCase().includes('nace'))) out.push('NACE MR-0175')
  if (s.options.some(o => o.toLowerCase().includes('locking'))) out.push('Locking Device')
  if (s.options.some(o => o.toLowerCase().includes('cavity'))) out.push('Cavity Filler Seat')
  return out
}