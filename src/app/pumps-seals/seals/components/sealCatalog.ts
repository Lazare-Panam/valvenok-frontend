// Helper to keep RFQ entries DRY — auto-builds rfqProduct from card metadata.
const makeRfqOnly = (
  base: Category & { rfqName?: string; rfqDescription?: string; keySpecs: { label: string; value: string }[] }
): SealModelEntry => ({
  code: base.code,
  title: base.title,
  subtitle: base.subtitle,
  description: base.description,
  specs: base.specs,
  applications: base.applications,
  href: base.href,
  image: base.image,
  kind: 'rfq',
  rfqProduct: {
    id: base.code,
    name: base.rfqName ?? `${base.code} — ${base.subtitle}`,
    brand: 'Valvenok',
    category: 'Mechanical Seals',
    categoryId: 'mechanical-seals',
    thumbnail: base.image,
    description: base.rfqDescription ?? base.description,
    keySpecs: base.keySpecs,
    variantInfo: { count: 0, sizeRange: 'Various' },
  },
})

